/*
 * FLEX RX - receives Motorola FLEX pager transmissions at 1600 bit/s, 2-level
 * FSK (FLEX 1600/2, as the Dutch P2000 network sends them on 169.650 MHz), in
 * software, and keeps the last eight pages, shown one at a time: address
 * (capcode), text, type. The mode of every frame heard (1600/2, 3200/2,
 * 3200/4, 6400/4: the first sync and the frame information word are always
 * sent at 1600/2) is shown with key 3; only 1600/2 frames are decoded. Tune
 * the VFO (FM, wide; 169.650 MHz for P2000), then launch.
 *
 * The receiver and the audio path are POCSAG RX's: RAW receive (RX HPF300 /
 * LPF3K / de-emphasis and AFC off), PA4 read at 12.8 kHz (8 samples a bit),
 * DC removal, the sum of the last 4 samples (half a bit), 3 hysteresis
 * slicers at 1/4, 3/8 and 1/2 of the peak, each with its DPLL.
 *
 * FLEX (the frame layout follows the POCSAG/FLEX modem firmware, flexutils.cpp):
 * a frame lasts 1.875 s: bit sync (1010...), the 32-bit A word, B (16 bits),
 * A inverted, the frame information word (FIW), sync 2 (40 bits at 1600),
 * then 11 blocks of 256 bits, each 8 codewords sent interleaved (bit i of
 * word 0..7, then bit i+1...). A codeword is the BCH (31,21) of POCSAG plus a
 * parity bit, its 21 data bits sent first, least significant first. Each
 * slicer looks for A+B+/A of 1600/2 in either polarity (and of the other
 * modes, for key 3), checks the FIW (BCH and its 4-bit checksum), then
 * collects the 88 codewords; the slicers of one transmission share one frame
 * buffer, each word kept from the slicer that read it cleanly (or corrected).
 * At the end of the frame the block information word gives where the
 * addresses and their vectors are; each vector says where its message words
 * are and what they hold (alphanumeric: 3 x 7-bit characters a word,
 * numeric: 4-bit digits). A message sent to several capcodes in one frame
 * (P2000 alerts) is kept once, with the count of the other capcodes.
 *
 * Keys and the screen cost sample time. A FLEX network sends frame after
 * frame without a gap, so the screen is drawn in the 20 ms of bit sync that
 * starts each frame, right after the previous one is decoded (once every
 * 1.875 s); the keys are read every 100 ms (a 0.3 ms scan: the bit clocks run
 * on over it, the level held). Without traffic both are served every 100 ms.
 *
 * Keys (UV-K5 and UV-K1): UP/DOWN scroll the text a row when it overflows;
 *   pressed again at either end: the newer / older page · * normal view /
 *   compact view (saved) · 1 speaker on/off (saved, off by default; not gated
 *   by the squelch) · 2 clear · 3 bottom line: level, type and age of the page
 *   / the frame counters · 4 keyword beeps on/off (saved, on by default) ·
 *   EXIT quit.
 * A page holding one of the keywords of gen_assets.py (KW) beeps their count
 * (the most of those it holds; the list is empty until you fill it), once per
 * message, after it is drawn. MENU opens a
 * list of 4 capcodes (saved; 0-9 type, * clears, UP/DOWN the row, MENU or
 * EXIT back): a page to one of them beeps 5 times, even as one of the "+N"
 * capcodes of a message. With key 4 on,
 * only those pages wake the backlight; the others are drawn with the light
 * as it is. The green LED blinks for every page.
 * The loader re-runs RADIO_SetupRegisters on exit; the resident capture
 * (af_capture_close) restores the ADC, PA4, the DAC and its clock.
 */

